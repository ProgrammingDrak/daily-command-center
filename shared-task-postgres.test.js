const test = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const { createActivityDb } = require('./test-support/activity-db');
const { createActivityStore } = require('./activity-store');
const { createSharedTaskStore, SCHEMA_SQL } = require('./shared-task-store');
const W = require('./public/js/workout-model');
const owner = {userId:1,workspaceId:'ws-1'}, friend = {userId:2,workspaceId:'ws-2'};
const date = '2026-10-21';
test('shared participation PostgreSQL and real HTTP contracts', {skip:!process.env.DCC_PGLITE_MODULE && !process.env.DCC_TEST_DATABASE_URL},async t => {
  const ctx = await createActivityDb(); t.after(ctx.close);
  const socialStore = require('./social-store');
  Object.assign(ctx,{socialStore,APP_TIME_ZONE:'UTC',getTodayStr:()=>date,getScheduleBlocks:async()=>[],filterLegacyGcalBlocks:r=>r,isValidDate:()=>true});
  const broadcasts = []; ctx.broadcast=(type,data,workspaceId)=>broadcasts.push({type,data,workspaceId});
  const store = createSharedTaskStore(ctx), activity = createActivityStore(ctx); ctx.sharedTasks=store;
  await ctx.pool.query("INSERT INTO friendships(requester_id,addressee_id,status) VALUES(1,2,'accepted')");
  const make = async (on=date) => activity.create({title:'Synthetic morning workout',date:on,record:W.empty()},owner);
  const complete = (taskId,actor,mutationId,extra={}) => ctx.blockDB.setTaskCompletion({taskRef:taskId,workspaceId:actor.workspaceId,userId:actor.userId,completed:true,mutationId,...extra});
  const app = express();app.use(express.json());
  app.use((req,_res,next)=>{const mode=req.headers['x-test-user']; if(mode!=='none')req.session={userId:mode==='friend'?2:mode==='viewer'?3:1};req.workspaceId=mode==='friend'?'ws-2':'ws-1';next();});
  require('./routes/shared-tasks')(app,ctx);require('./routes/activity')(app,ctx);require('./routes/blocks')(app,ctx);
  const server=await new Promise(r=>{const s=app.listen(0,'127.0.0.1',()=>r(s));});t.after(()=>new Promise(r=>server.close(r)));
  const base='http://127.0.0.1:'+server.address().port;
  const request=async(path,{user='owner',method='GET',body}={})=>{const r=await fetch(base+path,{method,headers:{'content-type':'application/json','x-test-user':user},...(body?{body:JSON.stringify(body)}:{})});return {status:r.status,headers:r.headers,body:await r.json()};};

  await t.test('schema is additive and idempotent',async()=>{await ctx.pool.query(SCHEMA_SQL);await ctx.pool.query(SCHEMA_SQL);assert.equal((await store.list(owner)).length,0);});
  await t.test('addressed invites reveal only the occurrence until acceptance; retries create one task',async()=>{
    const task=await make();
    await ctx.pool.query("UPDATE blocks SET properties=properties || $2::jsonb WHERE id=$1",[task.taskId,{detail:'PRIVATE-NOTES-MARKER',repeatSeriesId:'repeat-secret',repeatOccurrenceKey:'2026-10-21'}]);
    const share=await store.invite(task.taskId,2,owner);assert.equal((await store.invite(task.taskId,2,owner)).id,share.id);
    const pending=(await store.list(friend)).find(s=>s.id===share.id);
    assert.equal(pending.state,'pending');assert.equal(pending.taskId,null);assert.deepEqual(pending.participants,[]);
    assert.doesNotMatch(JSON.stringify(pending),/PRIVATE-NOTES|repeat-secret|record|actual|source_task/);
    const [accepted,retry]=await Promise.all([store.respond(share.id,'accept',friend),store.respond(share.id,'accept',friend)]);
    assert.ok(accepted.taskId);assert.equal(accepted.taskId,retry.taskId);assert.notEqual(accepted.taskId,task.taskId);
    const copied=await ctx.blockDB.getBlock(accepted.taskId);
    assert.equal(copied.workspace_id,'ws-2');assert.equal(copied.properties.publicVisibility,'private');
    assert.equal(copied.properties.repeatSeriesId,undefined);assert.equal(copied.properties.detail,undefined);
    assert.equal((await store.list(owner)).find(s=>s.id===share.id).participants.length,2);
    await assert.rejects(store.invite(accepted.taskId,1,friend),{statusCode:403});
  });
  await t.test('reviewed instructions detach from custom catalogs and exclude measurements, provenance and logs',async()=>{
    const record=W.empty();record.plan=W.gentleReset(ctx.crypto.randomUUID);
    record.plan.exercises[0].sets[0].weight=987;record.plan.exercises[0].sets[0].reps=321;
    const task=await activity.create({title:'Synthetic guided workout',date,record},owner);
    const preview=await store.preview(task.taskId,owner);
    assert.ok(preview.instructions.exercises[0].movement.visualInstructions);
    await assert.rejects(store.preview(task.taskId,friend),{statusCode:404});
    await assert.rejects(store.invite(task.taskId,2,owner,{includeInstructions:true,instructionsHash:'stale'}),{statusCode:409});
    const share=await store.invite(task.taskId,2,owner,{includeInstructions:true,instructionsHash:preview.hash});
    const snapshot=(await store.list(friend)).find(s=>s.id===share.id).instructions;
    assert.equal(snapshot.exercises[0].sets[0].weight,null);assert.equal(snapshot.exercises[0].sets[0].reps,null);
    assert.ok(snapshot.exercises.every(e=>e.catalogExerciseId===null));
    const joined=await store.respond(share.id,'accept',friend),own=await activity.get(joined.taskId,friend);
    assert.equal(own.record.plan.exercises.length,10);assert.equal(W.guidanceSteps(own.record.plan).length,10);
    assert.deepEqual(own.record.actual,{sets:[],runs:[]});assert.equal(own.record.baseline,null);assert.equal(own.record.provenance,null);assert.deepEqual(own.record.session.events,[]);
    assert.notEqual(own.record.plan.exercises[0].id,record.plan.exercises[0].id);
    const guided=W.guide(own.record,'begin');
    await activity.save(joined.taskId,{record:guided,expectedRevision:1,mutationId:'recipient-guidance'},friend);
    assert.equal((await activity.get(joined.taskId,friend)).record.guidance.status,'active');
    const changed=structuredClone(record);changed.plan.exercises[0].movement.visualInstructions='PRIVATE LATER EDIT';
    await activity.save(task.taskId,{record:changed,expectedRevision:1,mutationId:'owner-plan-edit'},owner);
    assert.doesNotMatch(JSON.stringify((await store.list(friend)).find(s=>s.id===share.id)),/PRIVATE LATER EDIT/);
  });
  await t.test('one completion cannot hide or finish the other participant; exact replay is idempotent',async()=>{
    const task=await make(), share=await store.invite(task.taskId,2,owner), joined=await store.respond(share.id,'accept',friend);
    const first=await complete(task.taskId,owner,'owner-complete');assert.equal(first.duplicate,false);
    assert.equal((await complete(task.taskId,owner,'owner-complete')).duplicate,true);
    let seen=(await store.list(friend)).find(s=>s.id===share.id);
    assert.deepEqual(seen.participants.map(p=>p.completed).sort(),[false,true]);
    assert.equal(ctx.blockDB.isCompletedTaskProps((await ctx.blockDB.getBlock(joined.taskId)).properties),false);
    const friendDone=await complete(joined.taskId,friend,'friend-complete');
    seen=(await store.list(owner)).find(s=>s.id===share.id);assert.ok(seen.participants.every(p=>p.completed));
    await ctx.blockDB.setTaskCompletion({taskRef:joined.taskId,workspaceId:'ws-2',userId:2,completed:false,mutationId:'friend-reopen',expectedRevision:friendDone.revision});
    assert.equal(ctx.blockDB.isCompletedTaskProps((await ctx.blockDB.getBlock(task.taskId)).properties),true);
    assert.equal((await store.list(owner)).find(s=>s.id===share.id).participants.filter(p=>p.completed).length,1);
    await assert.rejects(complete(joined.taskId,friend,'stale-complete',{expectedRevision:friendDone.revision}),{statusCode:409});
  });
  await t.test('new recurring occurrence starts independently and private workout logs never cross users',async()=>{
    const first=await make(),second=await make('2026-10-22');
    for(const task of [first,second])await ctx.pool.query("UPDATE blocks SET properties=properties || $2::jsonb WHERE id=$1",[task.taskId,{repeatSeriesId:'same-series',repeatOccurrenceKey:task.date}]);
    const s1=await store.invite(first.taskId,2,owner),s2=await store.invite(second.taskId,2,owner);
    const p1=await store.respond(s1.id,'accept',friend),p2=await store.respond(s2.id,'accept',friend);
    const log=require('./test-support/activity-fixtures').workout(date);log.actual.runs[0].name='FRIEND-PRIVATE-WORKOUT';
    await activity.save(p1.taskId,{record:log,expectedRevision:0,mutationId:'own-log'},friend);
    await complete(first.taskId,owner,'repeat-owner-1');await complete(p1.taskId,friend,'repeat-friend-1');
    const seen=await store.list(friend);assert.notEqual(s1.id,s2.id);assert.notEqual(p1.taskId,p2.taskId);
    assert.ok(seen.find(s=>s.id===s1.id).participants.every(p=>p.completed));
    assert.ok(seen.find(s=>s.id===s2.id).participants.every(p=>!p.completed));
    assert.doesNotMatch(JSON.stringify(await store.list(owner)),/FRIEND-PRIVATE-WORKOUT/);
    assert.equal((await activity.get(p1.taskId,friend)).record.actual.runs[0].name,'FRIEND-PRIVATE-WORKOUT');
    assert.deepEqual((await activity.get(p2.taskId,friend)).record.actual.runs,[]);
    await assert.rejects(activity.get(p1.taskId,owner),{statusCode:404});
  });
  await t.test('real routes enforce sessions, workspace ownership, actor identity and private response headers',async()=>{
    const task=await make(),s=await store.invite(task.taskId,2,owner),p=await store.respond(s.id,'accept',friend);
    assert.equal((await request('/api/shared-tasks',{user:'none'})).status,401);
    assert.equal((await request('/api/shared-tasks',{user:'viewer'})).status,403);
    assert.match((await request('/api/shared-tasks')).headers.get('cache-control'),/private.*no-store/);
    assert.equal((await request('/api/shared-tasks/invite',{user:'friend',method:'POST',body:{taskId:task.taskId,userId:1}})).status,404);
    assert.equal((await request('/api/shared-tasks/'+s.id+'/respond',{user:'friend',method:'POST',body:{action:'remove',userId:1}})).status,404);
    for(const user of ['friend','viewer']){
      const r=await request('/api/tasks/'+task.taskId+'/completion',{user,method:'POST',body:{completed:true,mutationId:'forged-'+user}});
      assert.equal(r.status,user==='viewer'?403:404);
    }
    assert.equal((await request('/api/blocks/'+task.taskId,{user:'viewer',method:'PATCH',body:{properties:{status:'done'}}})).status,403);
    assert.equal((await request('/api/blocks/batch',{user:'viewer',method:'POST',body:{operations:[]}})).status,403);
    const r=await request('/api/tasks/'+p.taskId+'/completion',{user:'friend',method:'POST',body:{completed:true,mutationId:'real-route'}});
    assert.equal(r.status,200,JSON.stringify(r.body));
    assert.equal(ctx.blockDB.isCompletedTaskProps((await ctx.blockDB.getBlock(task.taskId)).properties),false);
    assert.equal((await request('/api/activity/tasks/'+task.taskId,{user:'friend'})).status,404);
  });
  await t.test('decline, removal and lost friendship revoke visibility without deleting personal history',async()=>{
    const task=await make(),s=await store.invite(task.taskId,2,owner);
    await store.respond(s.id,'decline',friend);
    assert.equal((await store.list(friend)).some(x=>x.id===s.id),false);
    await assert.rejects(store.respond(s.id,'accept',friend),{statusCode:404});
    await assert.rejects(store.invite(task.taskId,2,owner),{statusCode:409});
    const t2=await make(),s2=await store.invite(t2.taskId,2,owner),p=await store.respond(s2.id,'accept',friend);
    await complete(p.taskId,friend,'preserved-completion');
    await store.respond(s2.id,'remove',owner,2);
    assert.equal((await store.list(friend)).some(x=>x.id===s2.id),false);
    assert.equal(ctx.blockDB.isCompletedTaskProps((await ctx.blockDB.getBlock(p.taskId)).properties),true);
    await socialStore.blockUser(2,1);
    assert.deepEqual(await store.list(friend),[]);
    assert.ok((await store.list(owner)).every(x=>x.participants.every(p=>p.self)));
    await assert.rejects(store.invite((await make()).taskId,2,owner),{statusCode:403});
    await ctx.pool.query("DELETE FROM friendships WHERE status='blocked'");
  });
  await t.test('uninvited users and lost workspace ownership cannot read or accept participation',async()=>{
    await ctx.pool.query(`INSERT INTO users(id,username,created_at,updated_at) VALUES(4,'uninvited-demo',NOW(),NOW());
      INSERT INTO workspaces(id,name,slug,owner_id,created_at,updated_at) VALUES('ws-4','Other synthetic workspace','other-synthetic',4,NOW(),NOW());
      INSERT INTO workspace_members(workspace_id,user_id,role,created_at) VALUES('ws-4',4,'owner',NOW());
      INSERT INTO friendships(requester_id,addressee_id,status) VALUES(1,4,'accepted')`);
    const outsider={userId:4,workspaceId:'ws-4'}, task=await make(),s=await store.invite(task.taskId,2,owner);
    assert.deepEqual(await store.list(outsider),[]);
    await assert.rejects(store.respond(s.id,'accept',outsider),{statusCode:404});
    await assert.rejects(store.preview(task.taskId,outsider),{statusCode:404});
    await ctx.pool.query("DELETE FROM workspace_members WHERE workspace_id='ws-1' AND user_id=1");
    await assert.rejects(store.list(owner),{statusCode:403});
    assert.deepEqual(await store.list(friend),[]);
    await ctx.pool.query("INSERT INTO workspace_members(workspace_id,user_id,role,created_at) VALUES('ws-1',1,'owner',NOW())");
    assert.ok((await store.list(friend)).some(x=>x.id===s.id));
  });
  await t.test('SSE invalidations are payload-free, only to authorized owners, and tolerate duplicates',async()=>{
    const task=await make(),s=await store.invite(task.taskId,2,owner);await store.respond(s.id,'accept',friend);
    broadcasts.length=0;await store.notifyTask(task.taskId,'ws-1',ctx.broadcast);await store.notifyTask(task.taskId,'ws-1',ctx.broadcast);
    assert.equal(broadcasts.length,4);assert.deepEqual(new Set(broadcasts.map(b=>b.workspaceId)),new Set(['ws-1','ws-2']));
    assert.ok(broadcasts.every(b=>b.type==='shared-tasks-changed'&&Object.keys(b.data).length===0));
    broadcasts.length=0;await store.notifyTask(task.taskId,'ws-2',ctx.broadcast);assert.equal(broadcasts.length,0);
    await store.respond(s.id,'remove',owner,2);broadcasts.length=0;await store.notify(s.id,ctx.broadcast);
    assert.ok(broadcasts.every(b=>b.workspaceId==='ws-1'));
    await ctx.blockDB.deleteBlock(task.taskId);assert.equal((await store.list(owner)).some(x=>x.id===s.id),false);
  });
  await t.test('accept transaction rolls back all new rows when task creation fails',async()=>{
    const task=await make(),s=await store.invite(task.taskId,2,owner),before=(await ctx.pool.query('SELECT count(*) FROM blocks')).rows[0].count;
    const failing=createSharedTaskStore({...ctx,blockDB:{...ctx.blockDB,createItineraryTask:async()=>{throw new Error('synthetic disk failure');}}});
    await assert.rejects(failing.respond(s.id,'accept',friend),/synthetic disk failure/);
    assert.equal((await ctx.pool.query('SELECT count(*) FROM blocks')).rows[0].count,before);
    assert.equal((await store.list(friend)).find(x=>x.id===s.id).state,'pending');
    assert.ok((await store.respond(s.id,'accept',friend)).taskId);
  });
});
