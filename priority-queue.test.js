const test = require('node:test');
const assert = require('node:assert/strict');
const { classify, orderPriority } = require('./lib/queue-classification');
const { command } = require('./lib/conversation-model');
const task = p => ({ id: 't', date: '2099-01-01', properties: { type: 'task', ...p } });
test('Priority Queue distinguishes plans, real starts and ambiguous legacy actuals without mutation', () => {
  const planned = task({ start: '10:00', end: '11:00', duration: 60, estimatedMinutes: 60, priority: 'urgent' });
  const before = JSON.stringify(planned);
  assert.equal(classify(planned), 'queued');
  for (const p of [{everStarted:true},{lastWorkedAt:'2026-10-01'},{actualMinutes:12},{actualMinutes:0},{actualMinutes:0,actualMinutesFrom:'derived'},{status:'in_progress'},{actualTimeUnknown:true}]) assert.equal(classify(task(p)), 'paused', JSON.stringify(p));
  assert.equal(classify(planned, {}, {session:true}), 'paused');
  assert.equal(classify(planned, {}, {delegated:true}), 'paused');
  assert.equal(classify(task({startedAt:'2026-10-01'}), {status:'queued'}), 'foreground');
  assert.equal(classify(task({done:true,startedAt:'2026-10-01'})), 'completed');
  assert.equal(classify(planned, {}, {dayRoot:{_done:{ids:['t']}}}), 'completed');
  for(const status of ['cancelled','canceled','deleted','skipped','archived']) assert.equal(classify(task({status})), null);
  assert.equal(classify({...planned,deleted_at:'2026-10-01'}), null);
  assert.equal(classify(task({kind:'responsibility_item'})), null);
  assert.equal(classify(task({responsibilityId:'r',occurrenceDate:'2099-01-01'})), 'queued');
  assert.equal(classify(task({responsibilityId:'r',everStarted:true})), 'paused');
  assert.equal(classify(planned,{status:'queued',hasActivity:true}), 'paused');
  assert.equal(JSON.stringify(planned), before);
});
test('priority is stable High/Medium/Low, never legacy urgency or scheduled time', () => {
  const rows=[['a','Low'],['b','High'],['c',undefined],['d','High']].map(([id,priority])=>({task:{...task({taskPriority:priority}),id}}));
  const before=JSON.stringify(rows);
  assert.deepEqual(orderPriority(rows).map(i=>i.task.id), ['b','d','c','a']);
  assert.equal(JSON.stringify(rows),before);
});
test('priority mutation requires a strict explicit command', () => {
  const b={action:'queue-priority',taskId:'t',sourceEventId:'p',expectedRevision:0,at:'2026-10-01T00:00:00Z',taskPriority:'High'};
  assert.equal(command(b).taskPriority,'High');
  assert.throws(()=>command({...b,taskPriority:'Urgent'}));
  assert.throws(()=>command({...b,action:'start'}));
});
test('Priority Queue coordinator lifecycle and legacy evidence', {skip:!process.env.DCC_TEST_DATABASE_URL&&!process.env.DCC_PGLITE_MODULE}, async t=>{
  const ctx=await require('./test-support/activity-db').createActivityDb();
  const old=process.env.DCC_CONVERSATION_ENABLED;process.env.DCC_CONVERSATION_ENABLED='true';
  t.after(async()=>{if(old===undefined)delete process.env.DCC_CONVERSATION_ENABLED;else process.env.DCC_CONVERSATION_ENABLED=old;await ctx.close();});
  const {createConversationStore,FOREGROUND_INDEX_SQL}=require('./conversation-store');
  await ctx.pool.query(FOREGROUND_INDEX_SQL);
  let now=Date.parse('2026-10-20T08:00:00Z'),seq=0;
  const owner={userId:1,workspaceId:'ws-1'},store=createConversationStore({...ctx,now:()=>now});
  const make=(id,p={})=>ctx.blockDB.createBlock({id,type:'block',date:'2026-10-20',user_id:1,workspace_id:'ws-1',properties:{type:'task',title:id,status:'open',...p}});
  const send=async(action,id,extra={})=>store.execute({action,...(id?{taskId:id}:{}),sourceEventId:'pq:'+seq++,expectedRevision:(await store.state(owner)).revision,at:new Date(now+=60000).toISOString(),...extra},owner);
  const entry=async id=>(await store.state(owner)).queue.items.find(i=>i.task.id===id);
  await make('scheduled',{start:'09:00',end:'10:00',duration:60,subtaskOf:'parent'});
  await make('background');await make('next-occurrence',{responsibilityId:'routine'});
  for(const id of ['scheduled','background','next-occurrence'])await send('queue-add',id);
  const original=(await ctx.blockDB.getBlock('scheduled')).properties;
  await send('queue-priority','scheduled',{taskPriority:'High'});
  assert.deepEqual((await ctx.blockDB.getBlock('scheduled')).properties,{...original,taskPriority:'High'});
  assert.equal((await entry('scheduled')).status,'queued');
  assert.equal((await store.state(owner)).queue.priorityOrder[0],'scheduled');
  await send('start','scheduled');assert.equal((await entry('scheduled')).status,'foreground');
  await send('pause','scheduled');assert.equal((await entry('scheduled')).status,'paused');
  await send('queue-block','scheduled');await send('queue-unblock','scheduled');assert.equal((await entry('scheduled')).status,'paused');
  await send('background-start','background');
  assert.equal((await entry('background')).status,'background');
  assert.equal((await ctx.blockDB.getBlock('background')).properties.actualMinutes,undefined);
  await send('background-stop','background');await send('queue-remove','background');await send('queue-add','background');
  assert.equal((await entry('background')).status,'paused');
  await send('done','scheduled');assert.equal((await entry('scheduled')).status,'completed');
  assert.equal((await entry('next-occurrence')).status,'queued');
  await make('legacy',{actualMinutes:0});await send('queue-add','legacy');assert.equal((await entry('legacy')).status,'paused');
  await make('ledger',{local_id:'ledger-alias'});await send('queue-add','ledger');
  await ctx.blockDB.createBlock({id:'entry',type:'time_entry',user_id:1,workspace_id:'ws-1',properties:{blockId:'ledger-alias',durSec:30}});
  assert.equal((await entry('ledger')).status,'paused');
  const savedBefore=JSON.stringify((await ctx.pool.query('SELECT state FROM work_rotations')).rows);
  await store.state(owner);assert.equal(JSON.stringify((await ctx.pool.query('SELECT state FROM work_rotations')).rows),savedBefore,'classification must not write history');
  await make('cancelled',{status:'cancelled'});await assert.rejects(send('queue-add','cancelled'),{statusCode:409});
  await ctx.blockDB.deleteBlock('next-occurrence');assert.equal(await entry('next-occurrence'),undefined);
});
