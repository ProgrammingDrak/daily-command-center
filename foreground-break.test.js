const test = require('node:test');
const assert = require('node:assert/strict');
const {randomUUID} = require('node:crypto');
const {createConversationStore, FOREGROUND_INDEX_SQL} = require('./conversation-store');
const {projectPublicQueue} = require('./lib/public-working-queue');
test('foreground break is durable, coordinated and never charged as work', {skip:!process.env.DCC_TEST_DATABASE_URL&&!process.env.DCC_PGLITE_MODULE}, async t=>{
  const ctx=await require('./test-support/activity-db').createActivityDb();
  const original=process.env.DCC_CONVERSATION_ENABLED;
  process.env.DCC_CONVERSATION_ENABLED='true';
  t.after(async()=>{if(original===undefined)delete process.env.DCC_CONVERSATION_ENABLED;else process.env.DCC_CONVERSATION_ENABLED=original;await ctx.close();});
  await ctx.pool.query(FOREGROUND_INDEX_SQL);
  let now=Date.parse('2026-11-04T10:00:00Z');
  const owner={userId:1,workspaceId:'ws-1'},store=createConversationStore({...ctx,now:()=>now,APP_TIME_ZONE:'UTC'});
  const make=async(id,props={})=>ctx.blockDB.createBlock({id,type:'block',date:'2026-11-04',user_id:1,workspace_id:'ws-1',properties:{type:'task',title:id,status:'open',duration:30,...props}});
  const body=async(action,taskId,extra={})=>({action,taskId,sourceEventId:randomUUID(),expectedRevision:(await store.state(owner)).revision,at:new Date(now).toISOString(),...extra});
  const send=async(action,id,extra={})=>store.execute(await body(action,id,extra),owner);
  const row=id=>ctx.blockDB.getBlock(id);
  const item=async id=>(await store.state(owner)).queue.items.find(x=>x.task.id===id);
  await make('focus',{notes:'Preserve context',subtaskOf:'parent'});await make('priority');await make('background');
  for(const id of ['priority','focus','background'])await send('queue-add',id);
  await send('background-start','background',{remindMinutes:30,attentionMode:'snooze'});
  await send('start','focus');now+=5*60000;
  const before=await store.state(owner),pause=await body('pause','focus');
  const paused=await store.execute(pause,owner);
  assert.equal(paused.entries.length,1);assert.equal(paused.task.properties.actualMinutes,5);
  assert.equal(paused.task.properties.startedAt,undefined);
  assert.equal(paused.state.foreground[0].id,'focus');assert.equal((await item('focus')).onBreak,true);
  assert.deepEqual(paused.state.queue.order,before.queue.order);
  for(const id of ['priority','background'])assert.deepEqual(paused.state.queue.items.find(x=>x.task.id===id),before.queue.items.find(x=>x.task.id===id));
  const breakAt=(await item('focus')).breakStartedAt;
  now+=4*60000;
  assert.equal((await store.execute(pause,owner)).duplicate,true);
  await send('pause','focus');assert.equal((await item('focus')).breakStartedAt,breakAt);
  assert.equal((await row('focus')).properties.actualMinutes,5);
  const restarted=createConversationStore({...ctx,now:()=>now,APP_TIME_ZONE:'UTC'});
  assert.equal((await restarted.state(owner)).queue.items.find(x=>x.task.id==='focus').onBreak,true);
  const projected=projectPublicQueue([{id:'public',blockId:'focus',title:'Public title',status:'open'}],(await store.state(owner)).queue);
  assert.equal(projected[0].queue.lane,'foreground');assert.equal(projected[0].queue.status,'paused');
  assert.equal(JSON.stringify(projected).includes('Preserve context'),false);assert.equal(JSON.stringify(projected).includes('breakStartedAt'),false);
  assert.equal(projectPublicQueue([{blockId:'focus',redacted:true}],(await store.state(owner)).queue).length,0);
  // Stale and simultaneous resume/pause are decided by the account revision.
  await assert.rejects(store.execute({...pause,sourceEventId:randomUUID()},owner),{statusCode:409});
  const resume=await body('start','focus',{expectedForegroundTaskId:null});
  const results=await Promise.allSettled([store.execute(resume,owner),store.execute({...resume,sourceEventId:randomUUID()},owner)]);
  assert.equal(results.filter(x=>x.status==='fulfilled').length,1);assert.equal(results.find(x=>x.status==='rejected').reason.statusCode,409);
  assert.equal((await item('focus')).onBreak,false);assert.equal((await row('focus')).properties.actualMinutes,5);
  now+=2*60000;await send('pause','focus');assert.equal((await row('focus')).properties.actualMinutes,7);
  const snapshot=await store.state(owner);
  const guided=require('./guided-store').createGuidedStore({...ctx,APP_TIME_ZONE:'UTC'});
  const definition=await guided.saveDefinition({id:randomUUID(),expectedRevision:0,definition:{title:'Review',goal:'Confirm sources',starterPrompt:'Read source',completionCriteria:'Confirmed outcome',checklist:[]}},owner);
  await make('guided-invalid',{guidedDefinitionId:definition.id});
  await send('queue-add','guided-invalid');
  const beforeFailed=await store.state(owner);
  await assert.rejects(send('start','guided-invalid',{expectedForegroundTaskId:'focus'}));
  assert.deepEqual((await store.state(owner)).foreground,beforeFailed.foreground);
  assert.equal((await item('focus')).breakStartedAt,beforeFailed.queue.items.find(x=>x.task.id==='focus').breakStartedAt);
  assert.equal((await row('focus')).properties.actualMinutes,7);
  // An interrupted switch rolls back without releasing the retained foreground.
  await assert.rejects(send('start','priority',{expectedForegroundTaskId:'wrong'}),{statusCode:409});
  assert.deepEqual((await store.state(owner)).foreground,snapshot.foreground);
  now+=60000;await send('start','priority',{expectedForegroundTaskId:'focus',remindMinutes:15,attentionMode:'snooze'});
  assert.equal((await item('focus')).snoozed,true);assert.equal((await item('focus')).status,'background');
  assert.equal((await item('focus')).status,'background');assert.equal((await item('focus')).onBreak,false);
  assert.equal((await row('focus')).properties.actualMinutes,7);
  now+=60000;await send('pause','priority');await send('done','priority');
  assert.equal((await item('priority')).status,'completed');assert.equal((await item('priority')).onBreak,false);
  await assert.rejects(send('start','priority'),{statusCode:409});
  now+=60000;await send('start','focus');now+=60000;await send('pause','focus');
  await send('queue-return','focus');assert.equal((await item('focus')).status,'queued');
  assert.equal((await store.state(owner)).foreground.length,0);
  now+=60000;await send('start','focus');now+=60000;await send('pause','focus',{attentionMode:'priority'});
  assert.equal((await item('focus')).status,'queued');assert.equal((await item('focus')).onBreak,false);
  // Failed network delivery retries the exact event after other work moves on.
  const late=await store.execute(pause,owner);assert.equal(late.duplicate,true);assert.equal(late.currentState.foreground.length,0);
  assert.equal((await row('focus')).properties.notes,'Preserve context');assert.equal((await row('focus')).properties.subtaskOf,'parent');
  assert.equal((await item('background')).snoozed,true);
  assert.equal((await ctx.blockDB.getTaskTimeEntries('focus','ws-1')).length,4);
  await ctx.pool.query("INSERT INTO workspaces(id,name,slug,owner_id,created_at,updated_at) VALUES('ws-extra','Extra','extra',1,NOW(),NOW()); INSERT INTO workspace_members(workspace_id,user_id,role,created_at) VALUES('ws-extra',1,'owner',NOW())");
  await ctx.blockDB.createBlock({id:'extra',type:'block',user_id:1,workspace_id:'ws-extra',properties:{type:'task',title:'Extra',status:'open'}});
  const other={userId:1,workspaceId:'ws-extra'};
  const startOther=async()=>store.execute({action:'start',taskId:'extra',sourceEventId:randomUUID(),expectedRevision:(await store.state(other)).revision,at:new Date(now).toISOString()},other);
  now+=60000;await send('start','focus');now+=60000;await send('pause','focus');
  assert.equal((await store.state(other)).otherWorkspaceForeground,true);
  await assert.rejects(startOther(),{statusCode:409});
  await send('queue-return','focus');assert.equal((await store.state(other)).otherWorkspaceForeground,false);
  now+=60000;await startOther();now+=60000;
  await store.execute({action:'pause',attentionMode:'priority',taskId:'extra',sourceEventId:randomUUID(),expectedRevision:(await store.state(other)).revision,at:new Date(now).toISOString()},other);
  now+=60000;await send('start','focus');now+=60000;await send('pause','focus');
  await send('done','focus');assert.equal((await store.state(other)).otherWorkspaceForeground,false);
  await make('deleted-break');now+=60000;await send('start','deleted-break');now+=60000;await send('pause','deleted-break');
  await ctx.blockDB.deleteBlock('deleted-break');assert.equal((await store.state(other)).otherWorkspaceForeground,false);
  // Completion revision invalidates a retained break after out-of-band completion/reopen.
  await make('changed-break');now+=60000;await send('start','changed-break');now+=60000;await send('pause','changed-break');
  await ctx.pool.query("UPDATE blocks SET properties=properties || '{\"_completionRevision\":\"external\"}'::jsonb WHERE id='changed-break'");
  assert.equal((await item('changed-break')).onBreak,false);
  assert.equal((await store.state(other)).otherWorkspaceForeground,false);
});
