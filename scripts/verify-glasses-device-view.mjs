async function ready(glasses=true){
  await page.goto(base+'/?'+(glasses?'device=glasses':''));
  await page.waitForSelector('#list-view .it-list-item');
  if(glasses)await page.waitForSelector('#list-view .glasses-more',{state:'attached'});
  await page.waitForFunction(()=>document.querySelector('#unscheduled-pill-nav-count')?.textContent==='1');
}
async function snapshot(){
  return page.evaluate(()=>{
    const m=_itineraryListModel();
    const ids=items=>items.map(item=>item.id).sort();
    return {date:m.viewDate,eligible:ids(m.day.visible),timed:ids(m.day.timed),unscheduled:ids(m.day.unscheduled),folded:ids(m.day.folded),
      rendered:[...document.querySelectorAll('#list-view .it-list-item')].map(e=>({id:e.dataset.id,done:e.classList.contains('done'),indent:e.style.marginLeft})),
      pills:[...document.querySelectorAll('#queue-pill button')].map(e=>({id:e.id,count:e.querySelector('.queue-seg-count').textContent,hidden:e.hidden}))};
  });
}
